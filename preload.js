const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lassu', {
  getState: () => ipcRenderer.invoke('get-state'),
  mark: (key, status) => ipcRenderer.invoke('mark', key, status),
  snooze: key => ipcRenderer.invoke('snooze', key),
  startSession: key => ipcRenderer.invoke('start-session', key),
  stopSession: () => ipcRenderer.invoke('stop-session'),
  sessionSize: big => ipcRenderer.send('session-size', big),
  takeResult: () => ipcRenderer.invoke('take-result'),
  hidePanel: () => ipcRenderer.send('hide-panel'),
  copy: text => ipcRenderer.send('copy', text),
  onState: cb => ipcRenderer.on('state', (_e, s) => cb(s)),
  onPanelOpened: cb => ipcRenderer.on('panel-opened', () => cb()),
  onClink: cb => ipcRenderer.on('clink', () => cb()),
  onResult: cb => ipcRenderer.on('result', (_e, r) => cb(r)),
  cardHeight: (h, slot) => ipcRenderer.send('card-height', h, slot),
  cardDismiss: key => ipcRenderer.send('card-dismiss', key),
  cardHold: (on, slot) => ipcRenderer.send('card-hold', on, slot),
  cardPreviewed: key => ipcRenderer.send('card-previewed', key),
  openPanel: () => ipcRenderer.send('open-panel'),
  capture: entry => ipcRenderer.invoke('capture', entry),
  todayCaptures: () => ipcRenderer.invoke('today-captures'),
  warmup: key => ipcRenderer.invoke('warmup', key),
  quizAnswer: (id, correct) => ipcRenderer.invoke('quiz-answer', id, correct),
  quizAdd: entry => ipcRenderer.invoke('quiz-add', entry),
  tokenize: text => ipcRenderer.invoke('tokenize', text),
  weekReview: () => ipcRenderer.invoke('week-review'),
  readUpTo: (habitId, n) => ipcRenderer.invoke('read-up-to', habitId, n),
  keepCapture: line => ipcRenderer.invoke('keep-capture', line),
  peek: (key, rowTop) => ipcRenderer.send('peek', key, rowTop),
  peekHide: () => ipcRenderer.send('peek-hide'),
  peekHeight: h => ipcRenderer.send('peek-height', h),
  onPeekItem: cb => ipcRenderer.on('peek-item', (_e, item) => cb(item)),
  onCardNew: cb => ipcRenderer.on('card-new', () => cb()),
  onEyes: cb => ipcRenderer.on('eyes', (_e, e) => cb(e)),
  eyesDone: () => ipcRenderer.send('eyes-done'),
  eyesSkip: () => ipcRenderer.send('eyes-skip'),
  onAutoBranded: cb => ipcRenderer.on('auto-branded', (_e, item) => cb(item)),
});
